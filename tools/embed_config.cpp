// build-time tool: embed_config <config_dir> <out.cpp>
// every file under config_dir -> obfuscated byte array + table entry.
#include <algorithm>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <iterator>
#include <string>
#include <vector>
#include "ConfigCipher.h"

namespace fs = std::filesystem;

int main(int argc, char** argv) {
    if (argc < 3) { std::cerr << "usage: embed_config <config_dir> <out.cpp>\n"; return 1; }
    fs::path root = argv[1];
    std::vector<fs::path> files;
    for (const auto& e : fs::recursive_directory_iterator(root))
        if (e.is_regular_file()) files.push_back(e.path());
    std::sort(files.begin(), files.end());

    std::ofstream out(argv[2]);
    if (!out) { std::cerr << "cannot write " << argv[2] << "\n"; return 1; }
    out << "// GENERATED by tools/embed_config.cpp. do not edit.\n#include \"ConfigStore.h\"\n\n";

    std::vector<size_t> sizes;
    for (size_t i = 0; i < files.size(); ++i) {
        std::ifstream in(files[i], std::ios::binary);
        std::vector<char> data((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
        sizes.push_back(data.size());
        out << "static const unsigned char d" << i << "[] = {";
        for (size_t j = 0; j < data.size(); ++j) {
            if (j % 32 == 0) out << "\n";
            out << static_cast<int>(static_cast<unsigned char>(data[j]) ^ configKey(j, i)) << ",";
        }
        if (data.empty()) out << "0";
        out << "};\n";
    }
    out << "\nconst EmbeddedFile kEmbeddedFiles[] = {\n";
    for (size_t i = 0; i < files.size(); ++i)
        out << "  {\"" << fs::relative(files[i], root).generic_string() << "\", d" << i << ", " << sizes[i] << "},\n";
    if (files.empty()) out << "  {\"\", nullptr, 0},\n";
    out << "};\nconst size_t kEmbeddedFileCount = " << files.size() << ";\n";
    return 0;
}
